"""Print CCTBX's automatic-link metal target tables as Rust constants."""

import hashlib
import importlib.metadata
from pathlib import Path

from mmtbx.monomer_library import bondlength_defaults as source

print("//! Generated by tools/gen_validation_metal_defaults.py; do not edit.")
print(f"//! CCTBX {importlib.metadata.version('cctbx-base')}; source SHA256 {hashlib.sha256(Path(source.__file__).read_bytes()).hexdigest()}.")
print("pub const RESIDUE: &[(&str, &str, &str, f64, f64)] = &[")
for metal, elements in sorted(source.metal_defaults.items()):
    for element, residues in sorted(elements.items()):
        for residue, (target, sigma) in sorted(residues.items()):
            if target is not None and sigma is not None:
                print(f'    ("{metal.upper()}", "{element.upper()}", "{residue}", {float(target)!r}, {float(sigma)!r}),')
print("];")
for label, values in (("CARBONYL", source.carbonyl), ("OTHER", source.non_protein)):
    print(f"pub const {label}: &[(&str, &str, f64, f64)] = &[")
    for key, (target, sigma) in sorted(values.items()):
        metal, element = key if isinstance(key, tuple) else (key, "O")
        print(f'    ("{metal.upper()}", "{element.upper()}", {float(target)!r}, {float(sigma)!r}),')
    print("];")
