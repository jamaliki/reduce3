"""Print the effective CCTBX MCL zinc keys, including their ordered names."""

import hashlib
import importlib.metadata
from pathlib import Path

from mmtbx.conformation_dependent_library import metal_coordination_library as source

print("//! Generated by tools/gen_validation_zinc_targets.py; do not edit.")
print(f"//! CCTBX {importlib.metadata.version('cctbx-base')}; source SHA256 {hashlib.sha256(Path(source.__file__).read_bytes()).hexdigest()}.")
print("pub type Target = ((usize, usize), &'static [&'static str], f64, f64);")
print("pub const TARGETS: &[Target] = &[")
for counts, rows in sorted(source.database["ZN"].items()):
    for names, values in sorted(rows.items()):
        keys = ", ".join(f'"{name}"' for name in names)
        print(f"    ({counts}, &[{keys}], {float(values[0])!r}, {float(values[1])!r}),")
print("];")
